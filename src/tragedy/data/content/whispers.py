"""The Prompter's three whispers per mishap kind (docs/DATA.md section 5), plus `generic`.

Every kind has exactly the same three-way shape, so the box always feels like a decision:

* `lean_in`   chain:true. Yes, and... It raises chaos and warmth: the risky, charming one, and the one that can start a
              yes-and chain. The shows_gold autopilot `lean_in` takes this option in every kind.
* `cover_up`  chaos <= -5. Pretend nothing happened. Safe and a touch cold.
* a third way with its own id, flavour and tag (blame the goose, ask the front row, count the cue...).

`line` is what the Prompter murmurs. No placeholders, no pronouns: it fits whoever is on stage. `keywords` map free text
onto an option (lowercase single words); the engine adds its own +2 for the personal touch.
"""

from __future__ import annotations


def _opt(id, label, hint, warmth, chaos, adds_tag, chain, line, keywords):
    return {
        "id": id,
        "label": label,
        "hint": hint,
        "effects": {"warmth": warmth, "chaos": chaos},
        "adds_tag": adds_tag,
        "chain": chain,
        "line": line,
        "keywords": list(dict.fromkeys(keywords)),
    }


# --- the retune from the fun audit --------------------------------------------------------------------------------
# Measured on 1,252 real decisions: "Yes, and..." was the best whisper in 100% of them (96% even with look-ahead), cover-up
# in 0%. The signature mechanic was a fake choice. So, applied to every kind below so they stay one consistent shape:
#   lean_in : a little less warm (-1, never below 2) and much louder (chaos x1.7, capped at the checker's 10): the charming gamble that tangles the strings
#   cover_up: warmer (+2, at most +1) and still calming: the sensible choice when the strings are tight
#   third way: unchanged (the middle path)
# together with CHAOS_DECAY 3 -> 2 in engine/show.py so chaos actually builds. Now lean wins while the stage is calm, cover-up
# once the tangle bites, and the third way when you can't tell: the player has to read the stage.
def _retuned(lean, cover, third):
    lean["effects"] = {"warmth": max(2, lean["effects"]["warmth"] - 1), "chaos": min(10, round(lean["effects"]["chaos"] * 1.7))}
    cover["effects"] = {"warmth": min(1, cover["effects"]["warmth"] + 2), "chaos": cover["effects"]["chaos"]}
    return lean, cover, third


def _kind(kind, lean, cover, third):
    return {"kind": kind, "options": list(_retuned(lean, cover, third))}


