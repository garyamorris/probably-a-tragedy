"""Deterministic dataset generator: ``content/*.py`` -> ``datasets/*.json[l]`` + ``datasets/MANIFEST.json``.

Convention: every module in ``tragedy.data.content`` exports ``DATASETS: dict[str, list | dict]``. ``collect()`` imports
them all (modules without ``DATASETS`` are helpers and are skipped; datasets nobody has written yet are simply absent).
``shows_gold`` is not authored: it comes from ``tragedy.data.gold.build_gold()`` when that module exists, and is built
LAST because the engine reads the other datasets from disk.

Output is a pure function of the content modules: ``json.dumps(indent=1, ensure_ascii=False)`` + trailing newline,
authored key order, ``.jsonl`` (one compact object per line) for the two row-stream datasets.
"""

from __future__ import annotations

import hashlib
import importlib
import json
import pkgutil
import traceback
from pathlib import Path
from typing import Any

from tragedy.data import loader

# ------------------------------------------------------------------------------------------------ the 15 datasets
ORDER: tuple[str, ...] = (
    "performers",
    "staff",
    "flaws",
    "mishaps",
    "whispers",
    "cues",
    "genres",
    "towns",
    "tastes",
    "critics",
    "playbill",
    "road_events",
    "almanac_seeds",
    "props",
    "shows_gold",
)
JSONL: frozenset[str] = frozenset({"almanac_seeds", "shows_gold"})
GENERATED: frozenset[str] = frozenset({"shows_gold"})  # not authored in content/, produced by tragedy.data.gold

DESCRIPTIONS: dict[str, str] = {
    "performers": "The eight playable puppets: skills, stage fright, roles, flaws, voices.",
    "staff": "Madame, the three Quills, Clipboard, Mrs. Gasket and the paper moon: the agents who talk but do not perform.",
    "flaws": "Character flaws: what sets each one off (tag triggers), how often, and which mishap kinds it causes.",
    "mishaps": "Everything that goes wrong on stage: one tiny story per mishap, with effects, calamity slug and animation.",
    "whispers": "The Prompter's three whispers for every mishap kind (Yes and / Cover it up / a third way).",
    "cues": "The six stage cues (lights, thunder, trapdoor, fog, spotlight, curtain): what they fit, and how they misfire.",
    "genres": "Five genres x five beats x 5-6 script variants: loglines, tags, props and dialogue.",
    "towns": "Thirty towns with tastes, expectations, landmarks and gossip (plus the Royal Opera House of Wibbling).",
    "tastes": "Twelve audience archetypes: hat, likes, hates and how readily they laugh, cry, gasp and boo.",
    "critics": "Five pigeon critics: what they weigh, how noisy they are, and their star-rated pull-quote templates.",
    "playbill": "Programme furniture: bio parts, headings, back-page filler, 'tonight in' and 'previously' lines.",
    "road_events": "Twenty things that happen on the road between towns, with choices and consequences.",
    "almanac_seeds": "Sixty legends that seed the Almanac of Calamities so it has lore from night one.",
    "props": "Thirty props: names, the tags they imply, and the sprite that draws them.",
    "shows_gold": "Regression ground truth: seeded shows with autopilot and expected star bands (generated by the engine).",
}
MANIFEST_NAME = "MANIFEST.json"


def file_name(name: str) -> str:
    return f"{name}.jsonl" if name in JSONL else f"{name}.json"


def default_out() -> Path:
    return loader.DATASET_DIR


# ------------------------------------------------------------------------------------------------ collection
def collect(*, skip_broken: bool = False) -> tuple[dict[str, Any], list[str]]:
    """Import every content module and merge their ``DATASETS``. Returns ``(data, problems)``.

    ``problems`` are human-readable (an import error with its location, a duplicate dataset, an unknown dataset name).
    With ``skip_broken`` a module that fails to import contributes nothing; otherwise the caller decides what to do.
    """
    from tragedy.data import content

    data: dict[str, Any] = {}
    owner: dict[str, str] = {}
    problems: list[str] = []
    for mod_info in sorted(pkgutil.iter_modules(content.__path__), key=lambda m: m.name):
        if mod_info.name.startswith("_"):
            continue
        qual = f"tragedy.data.content.{mod_info.name}"
        try:
            mod = importlib.import_module(qual)
        except Exception as exc:  # a half-written module must not hide everyone else's problems
            tb = traceback.extract_tb(exc.__traceback__)
            where = f" ({Path(tb[-1].filename).name}:{tb[-1].lineno})" if tb else ""
            problems.append(f"content/{mod_info.name}.py failed to import: {type(exc).__name__}: {exc}{where}")
            continue
        published = getattr(mod, "DATASETS", None)
        if published is None:
            continue  # helper module
        if not isinstance(published, dict):
            problems.append(
                f"content/{mod_info.name}.py: DATASETS must be a dict of name -> data, got {type(published).__name__}"
            )
            continue
        for name, rows in published.items():
            if name not in ORDER or name in GENERATED:
                problems.append(
                    f"content/{mod_info.name}.py publishes unknown dataset {name!r} (known: {', '.join(n for n in ORDER if n not in GENERATED)})"
                )
                continue
            if name in data:
                problems.append(
                    f"dataset {name!r} is published by both content/{owner[name]}.py and content/{mod_info.name}.py"
                )
                continue
            data[name] = rows
            owner[name] = mod_info.name
    data = {name: data[name] for name in ORDER if name in data}
    return data, problems


def _gold_module():
    """The lead's ``tragedy.data.gold`` or None when it has not been written yet."""
    try:
        return importlib.import_module("tragedy.data.gold")
    except ModuleNotFoundError as exc:
        if exc.name == "tragedy.data.gold":
            return None
        raise


def build_gold_rows() -> list[dict[str, Any]] | None:
    """Run the engine's autopilot to produce shows_gold rows (reads the datasets from ``datasets/``)."""
    mod = _gold_module()
    if mod is None or not hasattr(mod, "build_gold"):
        return None
    loader._load.cache_clear()  # datasets were just rewritten
    return list(mod.build_gold())


# ------------------------------------------------------------------------------------------------ rendering
def dumps(name: str, data: Any) -> str:
    """The exact text written to disk for one dataset."""
    if name in JSONL:
        return "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in data)
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"


def row_count(data: Any) -> int:
    return len(data) if isinstance(data, (list, dict)) else 0


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def render(data: dict[str, Any]) -> dict[str, str]:
    """``{file name: text}`` for the given datasets, in canonical order."""
    return {file_name(name): dumps(name, data[name]) for name in ORDER if name in data}


def manifest_from_dir(out: Path) -> dict[str, dict[str, Any]]:
    """``{name: {file, rows, sha256, description}}`` for every known dataset file that exists in ``out``."""
    manifest: dict[str, dict[str, Any]] = {}
    for name in ORDER:
        path = out / file_name(name)
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        rows = sum(1 for line in text.splitlines() if line.strip()) if name in JSONL else row_count(json.loads(text))
        manifest[name] = {
            "file": path.name,
            "rows": rows,
            "sha256": sha256_text(text),
            "description": DESCRIPTIONS[name],
        }
    return manifest


def manifest_text(manifest: dict[str, dict[str, Any]]) -> str:
    return json.dumps(manifest, indent=1, ensure_ascii=False) + "\n"


# ------------------------------------------------------------------------------------------------ build / check
def _selected(only: set[str] | None, name: str) -> bool:
    return only is None or name in only


def build(
    out: Path | None = None, *, only: set[str] | None = None, skip_gold: bool = False, skip_broken: bool = False
) -> tuple[list[str], list[str]]:
    """Write ``out/<name>.json[l]`` and ``out/MANIFEST.json``. Returns ``(messages, problems)``; problems non-empty = failure."""
    out = out or default_out()
    data, problems = collect(skip_broken=skip_broken)
    messages: list[str] = []
    if problems and not skip_broken:
        return messages, problems
    out.mkdir(parents=True, exist_ok=True)
    chosen = {name: rows for name, rows in data.items() if _selected(only, name)}
    for fname, text in render(chosen).items():
        (out / fname).write_text(text, encoding="utf-8")
    messages.append(f"wrote {len(chosen)} dataset(s) to {out}: {', '.join(chosen) or '(none)'}")
    missing = [n for n in ORDER if n not in data and n not in GENERATED and _selected(only, n)]
    if missing:
        messages.append(f"not written yet (no content module publishes them): {', '.join(missing)}")
    # shows_gold last: the engine reads the other datasets from disk
    if _selected(only, "shows_gold") and not skip_gold:
        if out.resolve() != default_out().resolve():
            messages.append("shows_gold skipped (the engine reads datasets/, not --out)")
        else:
            try:
                rows = build_gold_rows()
            except Exception as exc:
                problems.append(f"tragedy.data.gold.build_gold() failed: {type(exc).__name__}: {exc}")
                rows = None
            if rows is not None:
                (out / file_name("shows_gold")).write_text(dumps("shows_gold", rows), encoding="utf-8")
                messages.append(f"wrote shows_gold ({len(rows)} rows) from tragedy.data.gold")
            elif not problems:
                messages.append("shows_gold: tragedy.data.gold not written yet (skipped)")
    manifest = manifest_from_dir(out)
    (out / MANIFEST_NAME).write_text(manifest_text(manifest), encoding="utf-8")
    messages.append(f"{MANIFEST_NAME}: {len(manifest)} datasets, {sum(m['rows'] for m in manifest.values())} rows")
    return messages, problems


def drift(
    out: Path | None = None, *, only: set[str] | None = None, skip_gold: bool = False
) -> tuple[list[str], list[str]]:
    """Rebuild in memory and compare with ``out``. Returns ``(differences, problems)``."""
    out = out or default_out()
    data, problems = collect()
    diffs: list[str] = []
    if problems:
        return diffs, problems
    chosen = {name: rows for name, rows in data.items() if _selected(only, name)}
    rendered = render(chosen)
    for fname, text in rendered.items():
        path = out / fname
        if not path.exists():
            diffs.append(f"{fname}: missing on disk (run `python -m tragedy.data build`)")
        elif path.read_text(encoding="utf-8") != text:
            diffs.append(
                f"{fname}: differs from what the content modules generate (run `python -m tragedy.data build`)"
            )
    if _selected(only, "shows_gold") and not skip_gold and out.resolve() == default_out().resolve() and not diffs:
        try:
            rows = build_gold_rows()
        except Exception as exc:
            problems.append(f"tragedy.data.gold.build_gold() failed: {type(exc).__name__}: {exc}")
            rows = None
        if rows is not None:
            path = out / file_name("shows_gold")
            if not path.exists():
                diffs.append("shows_gold.jsonl: missing on disk (run `python -m tragedy.data build`)")
            elif path.read_text(encoding="utf-8") != dumps("shows_gold", rows):
                diffs.append(
                    "shows_gold.jsonl: differs from tragedy.data.gold.build_gold() (run `python -m tragedy.data build`)"
                )
    if not diffs and not problems:
        mpath = out / MANIFEST_NAME
        want = manifest_text(manifest_from_dir(out))
        if not mpath.exists() or mpath.read_text(encoding="utf-8") != want:
            diffs.append(f"{MANIFEST_NAME}: out of date (run `python -m tragedy.data build`)")
    return diffs, problems
